const quizKey = document.body.dataset.quiz || "great-people";
const quiz = quizSets[quizKey] || quizSets["great-people"];
const questions = quiz.questions;

const questionNumberEl = document.getElementById("question-number");
const questionTotalEl = document.getElementById("question-total");
const scoreEl = document.getElementById("score");
const bestScoreEl = document.getElementById("best-score");
const questionTextEl = document.getElementById("question-text");
const answersEl = document.getElementById("answers");
const feedbackEl = document.getElementById("feedback");
const explainMoreEl = document.getElementById("explain-more");
const teachingHintEl = document.getElementById("teaching-hint");
const learnMoreLinkEl = document.getElementById("learn-more-link");
const nextButton = document.getElementById("next-button");
const restartButton = document.getElementById("restart-button");

let currentIndex = 0;
let score = 0;
let answered = false;
let bestScore = Number(localStorage.getItem(quiz.storageKey) || "0");

questionTotalEl.textContent = String(questions.length);
bestScoreEl.textContent = String(bestScore);

function updateFeedback(type, message) {
  feedbackEl.className = `feedback ${type}`;
  feedbackEl.textContent = message;
}

function shuffleChoices(choices) {
  const shuffled = [...choices];

  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const randomIndex = Math.floor(Math.random() * (index + 1));
    [shuffled[index], shuffled[randomIndex]] = [shuffled[randomIndex], shuffled[index]];
  }

  return shuffled;
}

function renderQuestion() {
  const current = questions[currentIndex];
  answered = false;
  nextButton.disabled = true;
  questionNumberEl.textContent = String(currentIndex + 1);
  scoreEl.textContent = String(score);
  questionTextEl.textContent = current.question;
  answersEl.innerHTML = "";
  updateFeedback("", "Choose the best answer.");

  if (explainMoreEl) {
    explainMoreEl.hidden = true;
  }

  shuffleChoices(current.choices).forEach((choice) => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "answer-button";
    button.textContent = choice;
    button.addEventListener("click", () => handleAnswer(button, choice));
    answersEl.appendChild(button);
  });
}

function handleAnswer(button, choice) {
  if (answered) {
    return;
  }

  answered = true;
  const current = questions[currentIndex];
  const explanation = current.success.replace(/^(Correct|Yes|Right|Great|Good|Well done)\.\s*/, "");
  const buttons = [...answersEl.querySelectorAll(".answer-button")];

  buttons.forEach((item) => {
    item.disabled = true;
    if (item.textContent === current.answer) {
      item.classList.add("correct");
    }
  });

  if (choice === current.answer) {
    score += 1;
    scoreEl.textContent = String(score);
    button.classList.add("correct");
    updateFeedback("good", current.hint ? `Correct. ${explanation}` : current.success);
  } else {
    button.classList.add("wrong");
    updateFeedback("bad", `Good try. The answer is ${current.answer}. ${explanation}`);
  }

  if (explainMoreEl && current.hint && current.sourceUrl) {
    teachingHintEl.textContent = current.hint;
    learnMoreLinkEl.href = current.sourceUrl;
    learnMoreLinkEl.textContent = current.sourceLabel || "Learn more from the source";
    explainMoreEl.hidden = false;
  }

  nextButton.disabled = false;
}

function saveBestScore() {
  if (score > bestScore) {
    bestScore = score;
    localStorage.setItem(quiz.storageKey, String(bestScore));
    bestScoreEl.textContent = String(bestScore);
  }
}

function nextQuestion() {
  if (!answered) {
    return;
  }

  currentIndex += 1;

  if (currentIndex >= questions.length) {
    saveBestScore();
    questionNumberEl.textContent = String(questions.length);
    questionTextEl.textContent = "Quiz complete!";
    answersEl.innerHTML = "";
    updateFeedback(
      "good",
      `You scored ${score} out of ${questions.length}. Tap Play Again to try once more.`
    );
    nextButton.disabled = true;
    return;
  }

  renderQuestion();
}

function restartGame() {
  currentIndex = 0;
  score = 0;
  renderQuestion();
}

nextButton.addEventListener("click", nextQuestion);
restartButton.addEventListener("click", restartGame);

renderQuestion();
